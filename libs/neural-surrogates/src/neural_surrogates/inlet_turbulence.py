"""uDALES' inlet turbulence, added to a surrogate rollout at inference time.

A stepper rolled out on its own predictions loses the inlet turbulence: the
uDALES runs that made its training data inject digital-filter fluctuations at
the west face every ``time_step`` seconds (``pyudales.utils.inlet_turbulence_utils``),
and the network cannot invent that random signal. :class:`InletTurbulence`
replays the same forcing onto every predicted frame: the inflow that entered
during the frame's output interval, laid out downstream of the inlet face by
Taylor's hypothesis, in the building-free columns upstream of the geometry.

The fluctuations come from the same generator, seed and global record indices
as the uDALES run (``seed=None``), so a rollout and its truth share the forcing;
an integer seed draws a fresh realization per trajectory instead. Frame ``t``
of a corpus trajectory sits at solver time ``spinup + output_frequency * (t + 1)``
(the forward model drops the spinup frames and relabels). That holds for every
trajectory run on its own; the second sample of a repeated train geometry
continued the first one's solver clock, so its records are offset (not handled).

Only corpora of the archived generator
(``scripts/neural_surrogate/generate_random_geometries_training_data.py``,
``training_data.output_frequency`` in their config.yaml) are supported:
``scripts/surrogate/generate_data.py`` seeds per sample and runs samples back
to back on one model, and stores neither the seed nor the record offset.
"""

from __future__ import annotations

import warnings
from typing import Any

import numpy as np
import torch
import xarray as xr
from neural_surrogates.datasets._params import load_param_table

# &RUN dtmax of the uDALES case templates (geometries/*/namoptions.*). The
# solver's driver grid overshoots the run by enough records to cover it, and
# those records enter the mean speed that sets the AR(1) coefficient.
CASE_DTMAX = 1.0
# Floor on the advection speed (m/s): a calm or cross-wind layer only forces
# the cells next to the inlet instead of dividing by zero.
MIN_ADVECTION_SPEED = 0.1


class InletTurbulence:
    """Frozen-turbulence footprint of uDALES' inlet forcing, added to rollout
    predictions.

    ``footprint`` is ``(T, 3, nz, ny, n_cols)``: what is added to the
    predicted frame ``t`` (``[u, v, w]``, physical m/s) in the first ``n_cols``
    x-columns; frame 0 (never predicted) is zero.
    """

    def __init__(self, footprint: torch.Tensor) -> None:
        self.footprint = footprint
        self.columns = slice(0, footprint.shape[-1])

    def __call__(self, pred: torch.Tensor, frame: int) -> torch.Tensor:
        """``pred`` ``(B, 3, z, y, x)`` with the forcing of ``frame`` added to
        every batch member."""
        out = pred.clone()
        out[..., self.columns] += self.footprint[frame].to(pred)
        return out

    @classmethod
    def from_dataset(
        cls, data: Any, sample: int, seed: int | None = None
    ) -> "InletTurbulence":
        """The forcing of trajectory ``sample`` of ``data`` (a
        :class:`~neural_surrogates.datasets.transition.TransitionDataset`).

        Args:
            data: Dataset over a corpus generated by uDALES with
                ``model.forward_model.inlet_turbulence`` enabled.
            sample: Trajectory index in ``data``.
            seed: ``None`` replays the truth run's own realization; an integer
                draws a fresh one, ``derive_seed(f"{seed}_{split}_{sample}")``,
                on the same record timeline.
        """
        from omegaconf import OmegaConf
        from pyudales.utils.inflow_utils import angle_to_velocity
        from pyudales.utils.inlet_turbulence_utils import (
            driver_time_grid,
            is_inlet_turbulence_enabled,
            resolve_inflow_schedule,
            resolve_inlet_turbulence_config,
        )
        from pyudales.utils.vertical_profile import build_profile_shape

        from pyurbanair.dynamic_parameters.ar2_relaxation import build_knot_times
        from pyurbanair.utils.digital_filter import (
            CROSS_COMPONENT_ANISOTROPY,
            derive_seed,
            filtered_fluctuations,
        )

        if tuple(data.state_vars) != ("u", "v", "w"):
            raise ValueError(
                "InletTurbulence needs state_vars ('u', 'v', 'w'), got "
                f"{data.state_vars}"
            )
        config_path = data.root / "config.yaml"
        cfg = OmegaConf.load(config_path)
        turb = OmegaConf.select(cfg, "model.forward_model.inlet_turbulence")
        turb = OmegaConf.to_container(turb) if turb is not None else None
        if not is_inlet_turbulence_enabled(turb):
            raise ValueError(
                f"{config_path} has no enabled model.forward_model.inlet_turbulence "
                "block: inlet turbulence can only be replayed on a corpus uDALES "
                "generated with it."
            )
        turb = resolve_inlet_turbulence_config(turb)
        output_frequency = OmegaConf.select(cfg, "training_data.output_frequency")
        if output_frequency is None:
            raise ValueError(
                f"{config_path} has no training_data.output_frequency: only corpora "
                "of the archived generator record the timeline the forcing needs "
                "(scripts/surrogate/generate_data.py stores no per-sample seed or "
                "record offset)."
            )
        output_frequency = float(output_frequency)
        profile_config = OmegaConf.select(
            cfg, "model.forward_model.nudging_config.profile_config"
        )
        if profile_config is not None:
            profile_config = OmegaConf.to_container(profile_config)

        with xr.open_dataset(data._state_files[sample]) as ds:
            spinup = ds.attrs.get("spinup_time_s")
            zt, yt, xt, stamps = (
                np.asarray(ds[c].values, dtype=float)
                for c in ("zt", "yt", "xt", "time")
            )
        if spinup is None:
            raise ValueError(
                f"{data._state_files[sample]} has no 'spinup_time_s' attr, so its "
                "frames cannot be placed on the solver's driver-record timeline."
            )
        spinup = float(spinup)
        n_frames, nz, ny = len(stamps), len(zt), len(yt)
        dz, dy, dx = zt[1] - zt[0], yt[1] - yt[0], xt[1] - xt[0]
        if not all(np.allclose(np.diff(c), d) for c, d in ((zt, dz), (yt, dy))):
            raise ValueError("InletTurbulence needs a uniform z and y grid.")
        zsize = nz * dz
        heights = (np.arange(nz) + 0.5) * dz  # solver zt (and zm below)

        # The corpus' own inflow parameters, whatever the model was trained on.
        param_path = data.root / "param" / data.split / data._state_files[sample].name
        table, names = load_param_table(param_path, n_frames, None, torch.float64)
        missing = {"inflow_angle", "velocity_magnitude"} - set(names)
        if missing:
            raise ValueError(f"{param_path} has no {sorted(missing)}.")
        params = table.numpy()
        angle = params[:, names.index("inflow_angle")]
        speed = params[:, names.index("velocity_magnitude")]
        if "vertical_inflow_exponent" in names:  # the solver's per-member alpha
            alpha = float(params[0, names.index("vertical_inflow_exponent")])
            profile_config = {
                "type": "power_law",
                **(profile_config or {}),
                "alpha": alpha,
            }
        shape_t = build_profile_shape(profile_config, heights, zsize)
        shape_m = build_profile_shape(profile_config, np.arange(nz + 1) * dz, zsize)

        # The solver interpolated the sampler's knots, not this per-frame
        # series (which is those knots interpolated onto the frame stamps):
        # recover them exactly by least squares on the hat functions.
        simulation_time = n_frames * output_frequency
        spk = OmegaConf.select(cfg, "training_data.params_sampler.seconds_per_knot")
        knots = (
            stamps
            if spk is None
            else np.asarray(build_knot_times(0.0, simulation_time, float(spk)))
        )
        hats = np.stack([np.interp(stamps, knots, e) for e in np.eye(len(knots))], 1)
        if np.linalg.matrix_rank(hats) < len(knots):  # knots denser than frames
            knots, hats = stamps, np.eye(n_frames)
        knot_values = np.linalg.lstsq(hats, np.stack([angle, speed], 1), rcond=None)[0]
        schedule = xr.Dataset(
            {
                "inflow_angle": ("time", knot_values[:, 0]),
                "velocity_magnitude": ("time", knot_values[:, 1]),
            },
            coords={"time": knots},
        )
        knot_times, knot_angle, knot_speed = resolve_inflow_schedule(
            schedule, spinup, simulation_time
        )

        # Records spanning the frames' solver times; the AR(1) coefficient
        # takes the mean speed over the solver's WHOLE record grid.
        time_step = float(turb["time_step"])
        frame_times = spinup + output_frequency * (np.arange(n_frames) + 1)
        first = int(np.floor(frame_times[0] / time_step + 1e-9))
        last = int(np.ceil(frame_times[-1] / time_step - 1e-9)) + 1
        record_times = np.arange(first, last + 1) * time_step
        all_times = driver_time_grid(spinup + simulation_time, time_step, CASE_DTMAX)
        if seed is not None:
            seed = derive_seed(f"{seed}_{data.split}_{sample}")
        elif turb["seed"] is not None:
            seed = int(turb["seed"])
        else:  # as apply_inlet_turbulence: the member's experiment name
            expnr = OmegaConf.select(cfg, "model.forward_model.experiment_name")
            if expnr is None:
                raise ValueError(
                    f"{config_path} has no model.forward_model.experiment_name, "
                    "which seeded the truth's realization."
                )
            seed = derive_seed(str(expnr))
        fluct = filtered_fluctuations(
            seed=seed,
            start_index=first,
            times=record_times,
            speed=np.interp(all_times, knot_times, knot_speed),
            n_z=nz,
            n_y=ny,
            dz=dz,
            dy=dy,
            length_scale_x=float(turb["length_scale_x"]),
            length_scale_y=float(turb["length_scale_y"]),
            length_scale_z=float(turb["length_scale_z"]),
        )
        # Scaled as pyudales.utils.inlet_turbulence_utils.build_driver_planes
        # does (planes minus their mean profile); w from the faces to zt.
        intensity = float(turb["intensity"])
        record_speed = np.interp(record_times, knot_times, knot_speed)[:, None]
        sigma_u = intensity * record_speed * shape_t
        sigma_w = CROSS_COMPONENT_ANISOTROPY * intensity * record_speed * shape_m
        sigma_w[:, 0] = 0.0
        u = fluct["u"] * sigma_u[:, :, None]
        u -= u.mean(axis=(1, 2), keepdims=True)
        v = fluct["v"] * CROSS_COMPONENT_ANISOTROPY * sigma_u[:, :, None]
        w = fluct["w"] * sigma_w[:, :, None]
        planes = np.stack(
            [u, v, 0.5 * (w[:, :-1] + w[:, 1:])], axis=1, dtype=np.float32
        )

        # Building-free columns: upstream of the first column holding a solid
        # cell (levels that are solid everywhere, a ground layer, don't count).
        fluid = data.geometry_for(sample).numpy() > 0
        solid = ~fluid[fluid.any(axis=(1, 2))]
        built = solid.any(axis=(0, 1))
        n_free = int(np.argmax(built)) if built.any() else len(xt)
        distance = (np.arange(n_free) + 0.5) * dx  # cell centre - inlet face

        # Frame t holds, at distance d, the inflow that entered d / U_adv(z)
        # earlier; only the slice that entered during (t-1, t] is new.
        u_ref = np.asarray(
            angle_to_velocity(
                np.interp(frame_times, knot_times, knot_angle),
                np.interp(frame_times, knot_times, knot_speed),
            )[0]
        )
        advection = np.maximum(u_ref[:, None] * shape_t, MIN_ADVECTION_SPEED)
        lag = distance / advection[:, :, None]  # (T, nz, n_free)
        reached = lag < output_frequency
        reached[0] = False
        n_cols = int(reached.any(axis=(0, 1)).sum())
        if n_cols == 0:
            warnings.warn(
                f"{data._state_files[sample].name}: no building-free column next "
                "to the inlet, so no inlet turbulence is added.",
                stacklevel=2,
            )
        lag, reached = lag[..., :n_cols], reached[..., :n_cols]
        position = (frame_times[:, None, None] - lag) / time_step - first
        lower = np.clip(np.floor(position).astype(int), 0, len(record_times) - 2)
        weight = (position - lower).astype(np.float32)[..., None, None]
        levels = np.arange(nz)[None, :, None]
        # (T, nz, n_cols, 3, ny) -> (T, 3, nz, ny, n_cols)
        values = (1 - weight) * planes[lower, :, levels] + weight * planes[
            lower + 1, :, levels
        ]
        values = values * reached[..., None, None]
        footprint = values.transpose(0, 3, 1, 4, 2) * fluid[None, :, :, :n_cols]
        return cls(torch.from_numpy(footprint.astype(np.float32)))
