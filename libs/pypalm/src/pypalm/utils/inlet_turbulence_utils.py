"""Switchable inlet turbulence for PALM's ``inflow_outflow`` runs.

``inlet_turbulence.method`` picks one of two mechanisms:

``digital_filter`` (default) — a synthetic turbulent inflow
    The inflow planes ``inflow_plane_u/v/w(time_inflow, z, y)`` in the
    ``_dynamic`` driver carry the mean profile *plus* Xie & Castro (2008)
    digital-filter fluctuations, generated by the same code as uDALES' driver
    planes (:mod:`pyurbanair.utils.digital_filter`). PALM's ``turbulent_inflow``
    module with ``turbulent_inflow_method='read_from_file'`` imposes them on the
    dirichlet inflow face at every Runge-Kutta substep, linearly interpolated in
    time (``turbulent_inflow_mod.f90:1006-1230``), and balances the mass flux
    at the radiation outflow (``:476-536``). Intensity, length scales and seed
    are prescribed, the mean still comes from ``inflow_angle`` /
    ``velocity_magnitude`` / ``vertical_inflow_exponent`` (static or
    time-varying), and a warm-started window continues its member's turbulence
    history through the persisted clock.

``random_disturbances`` — PALM's built-in inflow disturbances
    ``create_disturbances`` + ``dt_disturb`` re-inject uncorrelated random u/v
    kicks of ``amplitude`` m/s into the strip
    ``[inflow_disturbance_begin, inflow_disturbance_end]`` for the whole run
    (``time_integration.f90:966-989``). Turbulence intensity and length scales
    are not prescribed: they are whatever the flow develops from grid-scale
    noise. On xie_and_castro the auto strip is x = 0-22 m, z = 5-9 m, i.e.
    inside the first building row rather than upstream of it. Kept to
    reproduce older runs (SGS Round 2).

Neither PALM alternative fits pypalm's staging (line numbers refer to the
vendored PALM 25.10 ``packages/palm/model/src/``):

- Recycling (``turbulent_inflow_method='recycle_*'``) needs
  ``initializing_actions='cyclic_fill'`` or ``'read_restart_data'``
  (``turbulent_inflow_mod.f90:337-343``, ``TUI0006``), i.e. a precursor run,
  and recycles toward a mean from that precursor, not toward the estimated
  inflow.
- The synthetic turbulence generator needs ``initializing_actions =
  'set_constant_profiles'`` or ``'read_restart_data'`` in idealized setups
  (``synthetic_turbulence_generator_mod.f90:390-396``, ``STG0004``) — which
  rules out pypalm's LOD=1 cold start and every warm start — plus an
  ``STG_PROFILES`` file (``STG0007``), and it excludes ``read_from_file``
  inflow (``turbulent_inflow_mod.f90:323-328``, ``TUI0005``), so
  time-varying inflow parameters could not reach the solver.

``initial_seed`` is independent of both: it is PALM's one-off random kick at
cold-start init (``init_3d_model.f90:1488``).

Namelist sections
-----------------
``inflow_disturbance_begin`` / ``inflow_disturbance_end`` live in
``&initialization_parameters`` (``parin.f90:222-223``); ``create_disturbances``,
``disturbance_amplitude``, ``disturbance_energy_limit``,
``disturbance_level_b/t`` and ``dt_disturb`` live in ``&runtime_parameters``
(``parin.f90:348-369``).
"""

